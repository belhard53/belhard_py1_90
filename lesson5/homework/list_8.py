'''
Дана матрица:

matrix = [
    [1, 2, 3],
    [4, 5, 6], 
    [7, 8, 9]
]

1 -  Повернуть на 90° по часовой стрелке
    [[7, 4, 1],
     [8, 5, 2],
     [9, 6, 3]]
2 -  Повернуть на 90° против часовой стрелке
    [[3, 6, 9]
     [2, 5, 8]
     [1, 4, 7]]



'''
matrix = [
    [1, 2, 3, 11],
    [4, 5, 6, 12], 
    [7, 8, 9, 13]
]

# по часовой
a = matrix[::-1]
a = zip(*a)

# против
b = list(zip(*matrix))[::-1]


print(*a, sep='\n')
print()
print(*b, sep='\n')

